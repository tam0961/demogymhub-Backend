/** Apps Script the owner pastes into the old Sheet's bound script and deploys as a web app; the app pulls the tabs from it. */
export function dumpScriptCode(secret: string): string {
  return [
    `const SECRET = '${secret}';`,
    "const TZ = 'Asia/Ho_Chi_Minh';",
    '',
    'function doGet(e) {',
    '  if (!e || !e.parameter || e.parameter.key !== SECRET) return out({ ok: false, error: \'key\' });',
    '  try {',
    '    return out({',
    '      ok: true,',
    "      members: rows('Members', 9),",
    "      registrations: rows('registrations', 12),",
    "      classes: rows('Thông tin lớp', 6),",
    "      schedule: rows('Schedule', 7),",
    '    });',
    '  } catch (err) {',
    '    return out({ ok: false, error: String(err) });',
    '  }',
    '}',
    '',
    'function doPost(e) {',
    '  try {',
    "    const b = JSON.parse((e && e.postData && e.postData.contents) || '{}');",
    "    if (b.key !== SECRET) return out({ ok: false, error: 'key' });",
    "    if (b.action !== 'upsert_member') return out({ ok: false, error: 'action' });",
    "    const sh = SpreadsheetApp.getActive().getSheetByName('Members');",
    "    if (!sh) return out({ ok: false, error: 'Khong co tab Members' });",
    '    const want = digits(b.phone);',
    "    if (want.length < 10) return out({ ok: false, error: 'phone' });",
    '    const v = sh.getDataRange().getValues();',
    '    for (let i = 1; i < v.length; i++) if (digits(v[i][1]) === want) return out({ ok: true, added: false });',
    '    const row = sh.getLastRow() + 1;',
    "    sh.getRange(row, 2).setNumberFormat('@');",
    "    sh.getRange(row, 1, 1, 6).setValues([[String(b.name || ''), want.slice(1), String(b.email || ''), '', 0, 0]]);",
    '    return out({ ok: true, added: true });',
    '  } catch (err) {',
    '    return out({ ok: false, error: String(err) });',
    '  }',
    '}',
    '',
    'function digits(x) {',
    "  let p = String(x === null || x === undefined ? '' : x).replace(/[^0-9]/g, '');",
    "  if (p.length === 9) p = '0' + p;",
    "  if (p.indexOf('84') === 0 && p.length === 11) p = '0' + p.slice(2);",
    '  return p;',
    '}',
    '',
    'function rows(tab, width) {',
    '  const sh = SpreadsheetApp.getActive().getSheetByName(tab);',
    '  if (!sh) return [];',
    '  const v = sh.getDataRange().getValues();',
    '  const res = [];',
    '  for (let i = 1; i < v.length; i++) {',
    '    const r = [];',
    '    let any = false;',
    '    for (let c = 0; c < width; c++) {',
    '      let x = v[i][c];',
    "      if (x instanceof Date) x = Utilities.formatDate(x, TZ, tab === 'Schedule' && c >= 2 ? 'HH:mm' : 'yyyy-MM-dd HH:mm:ss');",
    "      x = x === null || x === undefined ? '' : String(x);",
    '      if (x.trim() !== \'\') any = true;',
    '      r.push(x);',
    '    }',
    '    if (any) res.push(r);',
    '  }',
    '  return res;',
    '}',
    '',
    'function out(o) {',
    '  return ContentService.createTextOutput(JSON.stringify(o)).setMimeType(ContentService.MimeType.JSON);',
    '}',
  ].join(String.fromCharCode(10));
}
